import { Router } from 'express';
import adminRoutes from './modules/admin/admin.routes';
import auditRoutes from './modules/audit/audit.routes';
import authRoutes from './modules/auth/auth.routes';
import sessionRoutes from './modules/auth/sessions.routes';
import userRoutes from './modules/users/users.routes';
import { categories, merchants, rules } from './modules/categories/categories.routes';
import accountRoutes from './modules/accounts/accounts.routes';
import transactionRoutes from './modules/transactions/transactions.routes';
import upiRoutes from './modules/upi/upi.routes';
import incomeRoutes from './modules/income/income.routes';
import recurringRoutes from './modules/recurring/recurring.routes';
import expenseRoutes from './modules/expenses/expenses.routes';
import { expenseReceipts, receipts } from './modules/expenses/receipts.routes';
import { expenseSplits, splits } from './modules/expenses/splits.routes';
import budgetRoutes from './modules/budgets/budgets.routes';
import loanRoutes from './modules/loans/loans.routes';
import goalRoutes from './modules/goals/goals.routes';
import investmentRoutes from './modules/investments/investments.routes';
import { assets, liabilities, networth } from './modules/assets/assets.routes';
import { bills, subscriptions } from './modules/bills/bills.routes';
import notificationRoutes from './modules/notifications/notifications.routes';
import { registerNotificationHooks } from './modules/notifications/hooks';
import dashboardRoutes from './modules/dashboard/dashboard.routes';
import reportRoutes from './modules/reports/reports.routes';
import paymentMethodRoutes from './modules/payment-methods/payment-methods.routes';

/** Mounts every versioned API module under /api/v1. */
export function apiV1(): Router {
  registerNotificationHooks();
  const router = Router();
  router.use('/auth', authRoutes);
  router.use('/auth', sessionRoutes);
  router.use('/audit-logs', auditRoutes);
  router.use('/me', userRoutes);
  router.use('/categories', categories.router);
  router.use('/merchants', merchants.router);
  router.use('/categorization-rules', rules.router);
  router.use('/payment-methods', paymentMethodRoutes);
  router.use('/accounts', accountRoutes);
  router.use('/transactions', transactionRoutes);
  router.use('/upi', upiRoutes);
  router.use('/income', incomeRoutes);
  router.use('/recurring-rules', recurringRoutes);
  router.use('/expenses', expenseRoutes);
  router.use('/expenses', expenseReceipts.router);
  router.use('/expenses', expenseSplits.router);
  router.use('/receipts', receipts.router);
  router.use('/splits', splits.router);
  router.use('/budgets', budgetRoutes);
  router.use('/loans', loanRoutes);
  router.use('/goals', goalRoutes);
  router.use('/investments', investmentRoutes);
  router.use('/assets', assets.router);
  router.use('/liabilities', liabilities.router);
  router.use('/net-worth', networth.router);
  router.use('/bills', bills.router);
  router.use('/subscriptions', subscriptions.router);
  router.use('/notifications', notificationRoutes);
  router.use('/dashboard', dashboardRoutes);
  router.use('/reports', reportRoutes);
  router.use('/admin', adminRoutes);
  return router;
}
