import type { Knex } from 'knex';

/** Adds created_at/updated_at (timestamptz, default now()). */
export function timestamps(knex: Knex, t: Knex.CreateTableBuilder): void {
  t.timestamp('created_at', { useTz: true }).notNullable().defaultTo(knex.fn.now());
  t.timestamp('updated_at', { useTz: true }).notNullable().defaultTo(knex.fn.now());
}

/** Installs the trigger that maintains updated_at for a table. */
export async function updatedAtTrigger(knex: Knex, table: string): Promise<void> {
  await knex.raw(
    `CREATE TRIGGER ${table}_set_updated_at BEFORE UPDATE ON ${table} FOR EACH ROW EXECUTE FUNCTION set_updated_at()`,
  );
}

/** Money column: NUMERIC(19,4). Never use float/real/double precision for money. */
export function money(t: Knex.CreateTableBuilder | Knex.AlterTableBuilder, name: string) {
  return t.decimal(name, 19, 4);
}

/** UUID primary key generated by PostgreSQL. */
export function uuidPk(knex: Knex, t: Knex.CreateTableBuilder) {
  return t.uuid('id').primary().defaultTo(knex.raw('gen_random_uuid()'));
}
